// 這個題組用到哪些圖（老師頁上傳、檢查時用）：投影圖片（pic）、自己看圖（gallery）、題目帶的圖（img）
export function setImages(setId) {
  const set = SETS[setId];
  if (!set) return [];
  const ids = new Set();
  for (const q of set.questions) { if (q.img) ids.add(q.img); if (q.type === 'gallery') (q.images || []).forEach((x) => ids.add(x)); }
  return [...ids].sort();
}

export function findQuestion(setId, qid) {
  const set = SETS[setId];
  if (!set) return null;
  return set.questions.find((q) => q.id === qid) || null;
}
